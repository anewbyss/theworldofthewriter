// Bundles the shared reference library (shared/*.json) into both apps.
// Run from the repo root:  node tools/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../shared/${f}`, import.meta.url)));
const reference = {
  ...read("schemas.json"),
  narrativeStyles: read("narrative-styles.json"),
  culturePools: read("culture-pools.json"),
  religions: read("religions.json"),
  ...read("languages.json"),
  ...read("connections.json"),
  tropes: read("tropes.json"),
  ...read("library.json"),
  ...read("lore.json"),
};
const json = JSON.stringify(reference);

writeFileSync(
  new URL("../web/js/reference-data.js", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/*.json — do not edit by hand.\nwindow.WOW_REF = ${json};\n`
);

// A plain multi-line Swift string: escape backslashes so JSON escapes survive.
const pretty = JSON.stringify(reference, null, 1);
if (pretty.includes('"""')) throw new Error('reference JSON cannot contain """');
writeFileSync(
  new URL("../ios/WowBrainstorm.swiftpm/ReferenceData.swift", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/*.json — do not edit by hand.\nlet referenceJSON = """\n${pretty.replace(/\\/g, "\\\\")}\n"""\n`
);
// World economy data ships separately so the iPad decodes it only when its page opens.
const econ = readFileSync(new URL("../shared/economy.json", import.meta.url), "utf8").trim();
if (econ.includes('"""')) throw new Error('economy JSON cannot contain """');
writeFileSync(new URL("../web/js/economy-data.js", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/economy.json — do not edit by hand.\nwindow.WOW_ECON = ${econ};\n`);
writeFileSync(new URL("../ios/WowBrainstorm.swiftpm/EconomyData.swift", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/economy.json — do not edit by hand.\nlet economyJSON = """\n${econ.replace(/\\/g, "\\\\")}\n"""\n`);

// Real geography (borders, places, areas) also ships separately and loads on demand.
const geo = readFileSync(new URL("../shared/geo.json", import.meta.url), "utf8").trim();
if (geo.includes('"""')) throw new Error('geo JSON cannot contain """');
writeFileSync(new URL("../web/js/geo-data.js", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/geo.json — do not edit by hand.\nwindow.WOW_GEO = ${geo};\n`);
writeFileSync(new URL("../ios/WowBrainstorm.swiftpm/GeoData.swift", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/geo.json — do not edit by hand.\nlet geoJSON = """\n${geo.replace(/\\/g, "\\\\")}\n"""\n`);

console.log(`Reference library bundled: ${reference.narrativeStyles.length} styles, ${reference.culturePools.length} culture pools, ${reference.tropes.length} tropes.`);
