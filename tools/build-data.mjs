// Bundles the shared reference library (shared/*.json) into both apps.
// Run from the repo root:  node tools/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../shared/${f}`, import.meta.url)));
const reference = {
  ...read("schemas.json"),
  narrativeStyles: read("narrative-styles.json"),
  culturePools: read("culture-pools.json"),
  tropes: read("tropes.json"),
  ...read("library.json"),
};
const json = JSON.stringify(reference);

writeFileSync(
  new URL("../web/js/reference-data.js", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/*.json — do not edit by hand.\nwindow.WOW_REF = ${json};\n`
);

// A plain multi-line Swift string: escape backslashes so JSON escapes survive.
const pretty = JSON.stringify(reference, null, 1);
if (pretty.includes('"""')) throw new Error('reference JSON cannot contain """');
writeFileSync(
  new URL("../ios/WowBrainstorm.swiftpm/ReferenceData.swift", import.meta.url),
  `// GENERATED by tools/build-data.mjs from shared/*.json — do not edit by hand.\nlet referenceJSON = """\n${pretty.replace(/\\/g, "\\\\")}\n"""\n`
);
console.log(`Reference library bundled: ${reference.narrativeStyles.length} styles, ${reference.culturePools.length} culture pools, ${reference.tropes.length} tropes.`);
